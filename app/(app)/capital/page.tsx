import Link from "next/link";
import { requireUser } from "@/lib/auth";
import { canManage } from "@/lib/roles";
import {
  DEFAULT_WINDOW_DAYS,
  getOrganizationContext,
  listAssetSummaries,
  listDecisions,
} from "@/lib/queries/capital";
import { CALCULATION_DEFINITIONS, OPTION_LABEL, type CapitalOption } from "@/lib/capital/model";
import { formatDate, formatMoney, formatMoneyCompact, formatPercent, timeAgo } from "@/lib/format";
import { Badge, EmptyState, Meter, PageHeader, SectionHeading, Stat } from "@/components/ui";

const CONDITION_TONE: Record<string, "green" | "amber" | "red" | "slate"> = {
  excellent: "green",
  good: "green",
  fair: "amber",
  poor: "red",
};

const STATUS_TONE: Record<string, "green" | "amber" | "red" | "slate"> = {
  ready: "green",
  maintenance: "amber",
  suspended: "red",
  retired: "slate",
};

function riskFlags(asset: {
  utilisation: number | null;
  maintenanceCost: number;
  replacementCost: number | null;
  acquisitionCost: number | null;
  condition: string | null;
  expectedLifeYears: number | null;
  acquiredAt: string | null;
  openIncidents: number;
}): Array<{ label: string; tone: "red" | "amber" | "slate" }> {
  const flags: Array<{ label: string; tone: "red" | "amber" | "slate" }> = [];
  const replacement = asset.replacementCost ?? asset.acquisitionCost;
  if (asset.utilisation !== null && asset.utilisation < 0.15) flags.push({ label: "Low use", tone: "amber" });
  if (replacement !== null && replacement > 0 && asset.maintenanceCost / replacement > 0.15) {
    flags.push({ label: "Repair burden", tone: "red" });
  }
  if (asset.condition === "poor") flags.push({ label: "Poor condition", tone: "red" });
  if (asset.expectedLifeYears !== null && asset.acquiredAt) {
    const ageYears = (Date.now() - new Date(asset.acquiredAt).getTime()) / (365.25 * 24 * 3600_000);
    if (ageYears >= asset.expectedLifeYears) flags.push({ label: "Beyond life", tone: "red" });
  }
  if (asset.openIncidents > 0) flags.push({ label: `${asset.openIncidents} open incident(s)`, tone: "amber" });
  return flags;
}

export default async function CapitalPage() {
  const user = await requireUser();
  const organization = await getOrganizationContext(user.organizationId);
  if (!organization) {
    return (
      <div>
        <PageHeader title="Capital decisions" />
        <EmptyState title="Workspace not found" description="This account has no organisation attached." />
      </div>
    );
  }

  const [assets, decisions] = await Promise.all([
    listAssetSummaries(user.organizationId, organization.openHour, organization.closeHour, DEFAULT_WINDOW_DAYS),
    listDecisions(user.organizationId, 8),
  ]);

  const totalAcquisition = assets.reduce((total, asset) => total + (asset.acquisitionCost ?? 0), 0);
  const totalReplacement = assets.reduce(
    (total, asset) => total + (asset.replacementCost ?? asset.acquisitionCost ?? 0),
    0,
  );
  const totalUsed = assets.reduce((total, asset) => total + asset.usedHours, 0);
  const totalAvailable = assets.reduce((total, asset) => total + asset.availableHours, 0);
  const totalUnmet = assets.reduce((total, asset) => total + asset.unmetDemand, 0);
  const totalMaintenance = assets.reduce((total, asset) => total + asset.maintenanceCost, 0);
  const totalDowntime = assets.reduce((total, asset) => total + asset.downtimeHours, 0);
  const utilisation = totalAvailable > 0 ? totalUsed / totalAvailable : null;

  const flagged = assets
    .map((asset) => ({ asset, flags: riskFlags(asset) }))
    .filter((row) => row.flags.length > 0)
    .sort((a, b) => b.flags.length - a.flags.length);
  const missingCost = assets.filter((asset) => asset.acquisitionCost === null).length;
  const missingCondition = assets.filter((asset) => asset.condition === null).length;
  const decidedCount = decisions.filter((decision) => decision.status === "decided").length;

  return (
    <div>
      <PageHeader
        eyebrow="Equipment decisions"
        title="Capital decisions"
        description={`Evidence for buying, repairing, sharing, reallocating or retiring equipment. Figures cover the last ${DEFAULT_WINDOW_DAYS} days and are derived from booking, usage, maintenance and unmet-demand records.`}
        actions={
          <Link href="/resources" className="btn-secondary">
            Asset catalogue
          </Link>
        }
      />

      {organization.isDemo ? (
        <div className="mb-5 rounded-xl border border-violet-200 bg-violet-50 px-4 py-3 text-sm text-violet-900">
          <strong>Synthetic demo data.</strong> This workspace was generated by{" "}
          <code className="font-mono text-[12px]">npm run db:seed-demo</code>. Every asset, booking, repair and unmet
          request below is fictional and exists to demonstrate the workflow — no external system is connected.
        </div>
      ) : null}

      <div className="mb-5 grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
        <Stat
          label="Assets in scope"
          value={assets.length}
          hint={`${formatMoneyCompact(totalAcquisition)} recorded acquisition value`}
        />
        <Stat
          label="Utilisation"
          value={formatPercent(utilisation)}
          hint={`${Math.round(totalUsed)} used of ${Math.round(totalAvailable)} available hours`}
          tone="green"
        />
        <Stat
          label="Unmet demand"
          value={totalUnmet}
          hint="Refused or unavailable requests in the window"
          tone={totalUnmet > 0 ? "amber" : "slate"}
        />
        <Stat
          label="Maintenance spend"
          value={formatMoneyCompact(totalMaintenance)}
          hint={`${Math.round(totalDowntime)} downtime hours recorded`}
          tone={totalMaintenance > 0 ? "red" : "slate"}
        />
      </div>

      <section className="card mb-5">
        <div className="border-b border-line px-5 py-4">
          <SectionHeading
            title="Asset evidence"
            description="Utilisation is actual usage hours ÷ available hours. Select an asset to see its full evidence and the five alternatives."
          />
        </div>
        {assets.length === 0 ? (
          <div className="px-5 py-10">
            <EmptyState
              title="No assets with cost or lifecycle data yet"
              description="The capital workflow reads acquisition cost, condition and life expectancy from the asset catalogue. Add a demo workspace or fill those fields on an asset."
              action={
                <Link href="/resources" className="btn-primary">
                  Open asset catalogue
                </Link>
              }
            />
          </div>
        ) : (
          <div className="overflow-x-auto">
            <table className="table min-w-[1000px]">
              <thead>
                <tr>
                  <th>Asset</th>
                  <th>Department</th>
                  <th className="w-40">Utilisation</th>
                  <th className="text-right">Used / available</th>
                  <th className="text-right">Unmet</th>
                  <th className="text-right">Maintenance</th>
                  <th>Condition</th>
                  <th>Signals</th>
                  <th />
                </tr>
              </thead>
              <tbody>
                {assets.map((asset) => {
                  const flags = riskFlags(asset);
                  const tone = asset.utilisation === null ? "slate" : asset.utilisation >= 0.5 ? "green" : asset.utilisation >= 0.2 ? "amber" : "red";
                  return (
                    <tr key={asset.id}>
                      <td>
                        <p className="font-mono text-[10px] uppercase tracking-wide text-brand-600">{asset.code}</p>
                        <p className="text-sm font-medium">{asset.name}</p>
                        <div className="mt-1 flex flex-wrap items-center gap-1">
                          <Badge tone={STATUS_TONE[asset.status] ?? "slate"}>{asset.status}</Badge>
                          {asset.isDemo ? <Badge tone="violet">demo</Badge> : null}
                        </div>
                      </td>
                      <td className="text-xs text-muted">{asset.departmentName ?? "Unassigned"}</td>
                      <td>
                        <Meter value={(asset.utilisation ?? 0) * 100} tone={tone} />
                        <p className="mt-1 text-[11px] text-muted">{formatPercent(asset.utilisation)}</p>
                      </td>
                      <td className="text-right text-xs text-muted">
                        {Math.round(asset.usedHours)}h / {Math.round(asset.availableHours)}h
                      </td>
                      <td className="text-right text-xs">{asset.unmetDemand > 0 ? <span className="font-semibold text-amber-700">{asset.unmetDemand}</span> : <span className="text-muted">0</span>}</td>
                      <td className="text-right text-xs">
                        <p>{formatMoneyCompact(asset.maintenanceCost)}</p>
                        <p className="text-[10px] text-muted">{asset.maintenanceEvents} event(s)</p>
                      </td>
                      <td>
                        {asset.condition ? (
                          <Badge tone={CONDITION_TONE[asset.condition] ?? "slate"}>{asset.condition}</Badge>
                        ) : (
                          <span className="text-[11px] text-muted">not recorded</span>
                        )}
                        <p className="mt-1 text-[10px] text-muted">
                          {asset.acquiredAt ? `acquired ${formatDate(asset.acquiredAt)}` : "purchase date missing"}
                        </p>
                      </td>
                      <td>
                        {flags.length === 0 ? (
                          <span className="text-[11px] text-muted">none</span>
                        ) : (
                          <div className="flex flex-wrap gap-1">
                            {flags.map((flag) => (
                              <Badge key={flag.label} tone={flag.tone}>
                                {flag.label}
                              </Badge>
                            ))}
                          </div>
                        )}
                      </td>
                      <td className="text-right">
                        <Link href={`/capital/${asset.id}`} className="btn-secondary text-xs">
                          Assess
                        </Link>
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        )}
        <p className="border-t border-line px-5 py-3 text-[11px] text-muted">
          Replacement value across the portfolio: {formatMoney(totalReplacement)} (recorded quotes where present,
          otherwise acquisition cost × 1.15). {missingCost > 0 ? `${missingCost} asset(s) have no acquisition cost. ` : ""}
          {missingCondition > 0 ? `${missingCondition} asset(s) have no condition recorded.` : ""}
        </p>
      </section>

      <div className="grid gap-5 xl:grid-cols-[1.1fr_1fr]">
        <section className="card">
          <div className="border-b border-line px-5 py-4">
            <SectionHeading
              title="Assets needing attention"
              description="Flagged from the same records: low use, repair burden, poor condition, beyond expected life, open incidents."
            />
          </div>
          {flagged.length === 0 ? (
            <div className="px-5 py-8">
              <EmptyState title="No risk signals in this window" description="Every asset is used, within life and free of open incidents." />
            </div>
          ) : (
            <ul className="divide-y divide-line">
              {flagged.slice(0, 8).map(({ asset, flags }) => (
                <li key={asset.id} className="flex items-center justify-between gap-3 px-5 py-3">
                  <div className="min-w-0">
                    <p className="truncate text-sm font-medium">
                      <span className="font-mono text-[10px] text-brand-600">{asset.code}</span> {asset.name}
                    </p>
                    <p className="text-[11px] text-muted">
                      {formatPercent(asset.utilisation)} used · {formatMoneyCompact(asset.maintenanceCost)} maintenance ·{" "}
                      {asset.downtimeHours}h downtime
                    </p>
                  </div>
                  <div className="flex shrink-0 flex-wrap justify-end gap-1">
                    {flags.slice(0, 2).map((flag) => (
                      <Badge key={flag.label} tone={flag.tone}>
                        {flag.label}
                      </Badge>
                    ))}
                  </div>
                </li>
              ))}
            </ul>
          )}
        </section>

        <section className="card">
          <div className="border-b border-line px-5 py-4">
            <SectionHeading
              title="Decision records"
              description={`${decisions.length} recent record(s), ${decidedCount} decided. The recommendation is advisory; a person records the decision.`}
            />
          </div>
          {decisions.length === 0 ? (
            <div className="px-5 py-8">
              <EmptyState
                title="No decision records yet"
                description="Open an asset's evidence and generate a recommendation to start one."
              />
            </div>
          ) : (
            <ul className="divide-y divide-line">
              {decisions.map((decision) => (
                <li key={decision.id} className="px-5 py-3">
                  <div className="flex items-start justify-between gap-3">
                    <div className="min-w-0">
                      <Link href={`/capital/decisions/${decision.id}`} className="text-sm font-medium hover:underline">
                        {decision.assetCode} · {decision.assetName}
                      </Link>
                      <p className="text-[11px] text-muted">
                        Recommended {OPTION_LABEL[decision.recommendedOption as CapitalOption] ?? decision.recommendedOption} ·{" "}
                        {decision.confidence} confidence · {timeAgo(decision.createdAt)}
                      </p>
                      {decision.decisionOption ? (
                        <p className="mt-0.5 text-[11px] text-emerald-700">
                          Decided: {OPTION_LABEL[decision.decisionOption as CapitalOption] ?? decision.decisionOption}
                          {decision.decidedByName ? ` by ${decision.decidedByName}` : ""}
                        </p>
                      ) : null}
                    </div>
                    <Badge tone={decision.status === "decided" ? "green" : "amber"}>{decision.status}</Badge>
                  </div>
                </li>
              ))}
            </ul>
          )}
          {!canManage(user.role) ? (
            <p className="border-t border-line px-5 py-3 text-[11px] text-muted">
              Only administrators and facility managers can generate or record a decision.
            </p>
          ) : null}
        </section>
      </div>

      <section className="card-pad mt-5">
        <SectionHeading
          title="How these numbers are calculated"
          description="Every metric is computed from records in this workspace. Nothing on this page is a stored aggregate."
        />
        <dl className="grid gap-x-8 gap-y-3 sm:grid-cols-2">
          {CALCULATION_DEFINITIONS.map((definition) => (
            <div key={definition.label} className="border-t border-line pt-2">
              <dt className="text-xs font-semibold text-ink">{definition.label}</dt>
              <dd className="mt-0.5 text-[11px] leading-relaxed text-muted">{definition.definition}</dd>
            </div>
          ))}
        </dl>
        <div className="mt-4 rounded-lg border border-amber-200 bg-amber-50 px-3 py-2.5 text-[11px] text-amber-900">
          <strong>Limitations.</strong> Usage hours only count sessions that were checked in and out. Calendar days are
          assumed operable, so holidays depress utilisation. Repair costs exclude staff time. Unmet demand only captures
          requests the system saw. Option scores rank alternatives against available evidence — they are not
          probabilities, savings forecasts, or a substitute for a quotation.
        </div>
      </section>
    </div>
  );
}
