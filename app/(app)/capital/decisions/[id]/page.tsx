import Link from "next/link";
import { notFound } from "next/navigation";
import { requireUser } from "@/lib/auth";
import { canManage } from "@/lib/roles";
import { getDecision } from "@/lib/queries/capital";
import { OPTION_LABEL, OPTION_ORDER, type CapitalOption } from "@/lib/capital/model";
import { recordDecisionAction } from "@/lib/actions/decisions";
import { formatDateTime, formatMoney, formatPercent } from "@/lib/format";
import { Badge, Flash, PageHeader, SectionHeading } from "@/components/ui";
import { SubmitButton } from "@/components/submit-button";

// This page renders the STORED snapshot. It deliberately does not recompute
// anything: the record must read the same in a year as it did on the day.

type Snapshot = {
  facts?: Record<string, unknown>;
  demand?: Record<string, unknown>;
  capacity?: Record<string, unknown>;
  maintenance?: Record<string, unknown>;
  risk?: Record<string, unknown>;
  coverage?: Record<string, unknown>;
  missingData?: unknown;
};

type StoredAlternative = {
  option?: string;
  label?: string;
  score?: number;
  applicable?: boolean;
  summary?: string;
  costNow?: number | null;
  annualCost?: number | null;
  costPerUsedHour?: number | null;
  supportingEvidence?: string[];
  missingEvidence?: string[];
  caveats?: string[];
};

function obj(value: unknown): Record<string, unknown> {
  return value && typeof value === "object" && !Array.isArray(value) ? (value as Record<string, unknown>) : {};
}
function num(value: unknown): number | null {
  return typeof value === "number" && Number.isFinite(value) ? value : null;
}
function text(value: unknown): string | null {
  return typeof value === "string" && value.length > 0 ? value : null;
}
function list(value: unknown): string[] {
  return Array.isArray(value) ? value.filter((entry): entry is string => typeof entry === "string") : [];
}

function moneyOr(value: unknown): string {
  const parsed = num(value);
  return parsed === null ? "—" : formatMoney(parsed);
}

export default async function DecisionRecordPage({
  params,
  searchParams,
}: {
  params: Promise<{ id: string }>;
  searchParams: Promise<{ error?: string; ok?: string }>;
}) {
  const user = await requireUser();
  const { id } = await params;
  const query = await searchParams;
  const decision = await getDecision(user.organizationId, id);
  if (!decision) notFound();

  const canDecide = canManage(user.role);
  const snapshot = decision.evidence as Snapshot;
  const facts = obj(snapshot.facts);
  const demand = obj(snapshot.demand);
  const capacity = obj(snapshot.capacity);
  const maintenance = obj(snapshot.maintenance);
  const coverage = obj(snapshot.coverage);
  const missingData = list(snapshot.missingData);
  const alternatives = (Array.isArray(decision.alternatives) ? decision.alternatives : []) as StoredAlternative[];
  const recommended = OPTION_LABEL[decision.recommendedOption as CapitalOption] ?? decision.recommendedOption;
  const decided = decision.decisionOption
    ? OPTION_LABEL[decision.decisionOption as CapitalOption] ?? decision.decisionOption
    : null;
  const override = decision.status === "decided" && decision.decisionOption !== decision.recommendedOption;

  return (
    <div>
      <div className="mb-4 flex flex-wrap gap-3 text-xs font-medium">
        <Link href="/capital" className="text-muted hover:text-ink">
          ← Capital decisions
        </Link>
        <Link href={`/capital/${decision.resourceId}`} className="text-muted hover:text-ink">
          Current evidence for this asset →
        </Link>
      </div>

      <PageHeader
        eyebrow="Capital decision record"
        title={`${decision.assetCode} — ${decision.assetName}`}
        description={`Evidence window ${decision.windowDays} days · generated ${formatDateTime(decision.createdAt)}${
          decision.createdByName ? ` by ${decision.createdByName}` : ""
        }`}
        actions={
          <div className="flex flex-wrap items-center gap-2">
            <Badge tone={decision.status === "decided" ? "green" : "amber"}>{decision.status}</Badge>
            <Badge tone={decision.confidence === "high" ? "green" : decision.confidence === "medium" ? "amber" : "red"}>
              {decision.confidence} confidence
            </Badge>
            {decision.isDemoAsset ? <Badge tone="violet">demo data</Badge> : null}
          </div>
        }
      />

      <Flash error={query.error} ok={query.ok} />

      {decision.isDemoAsset ? (
        <div className="mb-5 rounded-xl border border-violet-200 bg-violet-50 px-4 py-2.5 text-[12px] text-violet-900">
          <strong>Synthetic demo record.</strong> The asset and its evidence were generated by the demo seeder. The
          decision, if recorded, is yours.
        </div>
      ) : null}

      <div className="grid gap-5 xl:grid-cols-[1.2fr_1fr]">
        <div className="space-y-5">
          <section className="card-pad">
            <SectionHeading
              title="Recommendation (system)"
              description="Produced by the rule-based comparison when this record was generated. It is advisory."
            />
            <div className="flex flex-wrap items-center gap-2">
              <Badge tone="violet">{recommended}</Badge>
            </div>
            <p className="mt-3 text-sm leading-relaxed text-ink/80">{decision.recommendationReason}</p>
          </section>

          <section className="card-pad">
            <SectionHeading
              title="Human decision"
              description="The only part of this record that changes the outcome. It cannot be recorded without a named person and a rationale."
            />
            {decision.status === "decided" ? (
              <div className="rounded-xl border border-emerald-200 bg-emerald-50 px-4 py-3">
                <p className="text-sm font-semibold text-emerald-900">{decided}</p>
                <p className="mt-1 text-xs text-emerald-900/85">
                  {decision.decidedByName ?? "unknown user"} · {decision.decidedAt ? formatDateTime(decision.decidedAt) : ""}
                  {override ? " · overrides the system recommendation" : " · matches the recommendation"}
                </p>
                <p className="mt-2 border-t border-emerald-200 pt-2 text-sm leading-relaxed text-emerald-900/90">
                  {decision.decisionRationale}
                </p>
              </div>
            ) : canDecide ? (
              <form action={recordDecisionAction} className="space-y-3">
                <input type="hidden" name="decision_id" value={decision.id} />
                <fieldset>
                  <legend className="label">Decision</legend>
                  <div className="space-y-1.5">
                    {OPTION_ORDER.map((option) => (
                      <label
                        key={option}
                        className="flex cursor-pointer items-start gap-2 rounded-lg border border-line bg-white px-3 py-2 hover:border-brand-300"
                      >
                        <input
                          type="radio"
                          name="option"
                          value={option}
                          defaultChecked={option === decision.recommendedOption}
                          required
                          className="mt-0.5"
                        />
                        <span className="text-sm">
                          {OPTION_LABEL[option]}
                          {option === decision.recommendedOption ? (
                            <span className="ml-2 text-[11px] text-brand-700">system recommendation</span>
                          ) : null}
                        </span>
                      </label>
                    ))}
                  </div>
                </fieldset>
                <div>
                  <label className="label" htmlFor="rationale">
                    Rationale (required, minimum 12 characters)
                  </label>
                  <textarea
                    id="rationale"
                    name="rationale"
                    rows={4}
                    required
                    minLength={12}
                    maxLength={2000}
                    className="input"
                    placeholder="Why this option, what you checked, and who else was consulted."
                  />
                </div>
                <SubmitButton className="btn-primary" pendingLabel="Recording…">
                  Record decision
                </SubmitButton>
                <p className="text-[11px] text-muted">
                  This writes your name and the timestamp to the immutable audit trail.
                </p>
              </form>
            ) : (
              <p className="rounded-lg border border-line bg-canvas px-3 py-3 text-xs text-muted">
                Pending. Only an administrator or facility manager can record the decision. Signed in as {user.name}.
              </p>
            )}
          </section>

          <section className="card">
            <div className="border-b border-line px-5 py-4">
              <SectionHeading
                title="Alternatives considered"
                description="Stored exactly as assessed when this record was generated."
              />
            </div>
            <div className="overflow-x-auto">
              <table className="table min-w-[760px]">
                <thead>
                  <tr>
                    <th>Option</th>
                    <th className="text-right">Score</th>
                    <th className="text-right">Cost now</th>
                    <th className="text-right">Per year</th>
                    <th className="text-right">Per used hour</th>
                  </tr>
                </thead>
                <tbody>
                  {alternatives.map((alternative) => (
                    <tr key={alternative.option ?? alternative.label}>
                      <td>
                        <p className="text-sm font-medium">{alternative.label ?? alternative.option}</p>
                        {alternative.summary ? (
                          <p className="mt-0.5 max-w-[420px] text-[11px] text-muted">{alternative.summary}</p>
                        ) : null}
                        {alternative.supportingEvidence && alternative.supportingEvidence.length > 0 ? (
                          <ul className="mt-1 space-y-0.5">
                            {alternative.supportingEvidence.map((item) => (
                              <li key={item} className="text-[11px] text-ink/70">
                                • {item}
                              </li>
                            ))}
                          </ul>
                        ) : (
                          <p className="mt-1 text-[11px] text-muted">No signal was triggered for this option.</p>
                        )}
                        {alternative.missingEvidence && alternative.missingEvidence.length > 0 ? (
                          <p className="mt-1 text-[11px] text-amber-800">
                            Missing: {alternative.missingEvidence.join(" ")}
                          </p>
                        ) : null}
                      </td>
                      <td className="text-right text-xs">
                        {typeof alternative.score === "number" ? alternative.score.toFixed(2) : "—"}
                        {alternative.applicable === false ? (
                          <p className="text-[10px] text-muted">not costable</p>
                        ) : null}
                      </td>
                      <td className="text-right text-xs">{moneyOr(alternative.costNow)}</td>
                      <td className="text-right text-xs">{moneyOr(alternative.annualCost)}</td>
                      <td className="text-right text-xs">{moneyOr(alternative.costPerUsedHour)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </section>
        </div>

        <div className="space-y-5">
          <section className="card-pad">
            <SectionHeading title="Evidence snapshot" description="As captured on the timestamp above." />
            <dl className="mt-1 space-y-1.5 text-sm">
              {[
                ["Utilisation", formatPercent(num(capacity.utilisation))],
                ["Used / available hours", `${Math.round(num(demand.usedHours) ?? 0)}h / ${Math.round(num(capacity.availableHours) ?? 0)}h`],
                ["Bookings / completed / no-shows", `${num(demand.bookings) ?? 0} / ${num(demand.completed) ?? 0} / ${num(demand.noShows) ?? 0}`],
                ["Unmet requests", num(demand.unmetTotal) ?? 0],
                ["Unmet from other departments", num(demand.unmetFromOtherDepartments) ?? 0],
                ["Maintenance spend", moneyOr(maintenance.cost)],
                ["Downtime hours", `${Math.round(num(maintenance.downtimeHours) ?? 0)}h`],
                ["Repair estimate", moneyOr(maintenance.repairEstimate)],
                ["Acquisition cost", moneyOr(facts.acquisitionCost)],
                ["Replacement cost", moneyOr(facts.replacementCost)],
                ["Replacement source", text(facts.replacementCostSource) ?? "—"],
                ["Remaining life", num(facts.remainingLifeYears) === null ? "unknown" : `${num(facts.remainingLifeYears)} years`],
                ["Condition", text(facts.condition) ?? "not recorded"],
              ].map(([label, value]) => (
                <div key={label as string} className="flex items-baseline justify-between gap-3">
                  <dt className="text-xs text-muted">{label}</dt>
                  <dd className="text-sm font-medium">{value}</dd>
                </div>
              ))}
            </dl>
          </section>

          <section className="card-pad">
            <SectionHeading title="Assumptions" description="Fixed planning inputs used by the calculation." />
            <dl className="space-y-1.5">
              {Object.entries(decision.assumptions).map(([key, value]) => (
                <div key={key} className="flex items-baseline justify-between gap-3">
                  <dt className="text-[11px] text-muted">{key.replace(/([A-Z])/g, " $1").toLowerCase()}</dt>
                  <dd className="text-[11px] font-medium text-ink/85">{String(value)}</dd>
                </div>
              ))}
            </dl>
          </section>

          <section className="card-pad">
            <SectionHeading title="Data coverage at capture" />
            <ul className="space-y-1 text-[11px] text-muted">
              <li>Bookings: {num(coverage.bookings) ?? 0}</li>
              <li>Usage sessions: {num(coverage.sessions) ?? 0}</li>
              <li>Maintenance records: {num(coverage.maintenanceRecords) ?? 0}</li>
              <li>Unmet-demand events: {num(coverage.unmetDemandEvents) ?? 0}</li>
            </ul>
            {missingData.length > 0 ? (
              <div className="mt-3 rounded-lg border border-amber-200 bg-amber-50 px-3 py-2">
                <p className="text-[10px] font-semibold uppercase tracking-wide text-amber-800">
                  Evidence gaps at capture
                </p>
                <ul className="mt-1 space-y-1">
                  {missingData.map((item) => (
                    <li key={item} className="text-[11px] leading-relaxed text-amber-900">
                      • {item}
                    </li>
                  ))}
                </ul>
              </div>
            ) : null}
          </section>

          <section className="card-pad">
            <SectionHeading title="Record integrity" />
            <ul className="space-y-1 text-[11px] text-muted">
              <li>Record id {decision.id}</li>
              <li>Created {formatDateTime(decision.createdAt)} by {decision.createdByName ?? "unknown"}</li>
              <li>
                {decision.status === "decided"
                  ? `Decided ${decision.decidedAt ? formatDateTime(decision.decidedAt) : ""} by ${decision.decidedByName ?? "unknown"}`
                  : "No human decision recorded yet"}
              </li>
              <li>Stored evidence is a snapshot; it is not rewritten when asset data changes.</li>
              <li>Deletion is blocked by the database, and every step is in the audit trail.</li>
            </ul>
          </section>
        </div>
      </div>
    </div>
  );
}
